CREATE TABLE theme (
    theme_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE course_theme (
    course_theme_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INTEGER NOT NULL,
    theme_id INTEGER NOT NULL,
    CONSTRAINT fk_course_theme_course
        FOREIGN KEY (course_id) REFERENCES course (course_id),
    CONSTRAINT fk_course_theme_theme
        FOREIGN KEY (theme_id) REFERENCES theme (theme_id)
);

CREATE TABLE region_course (
    region_course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_id INTEGER NOT NULL,
    course_id INTEGER NOT NULL,
    CONSTRAINT fk_region_course_region
        FOREIGN KEY (region_id) REFERENCES region (region_id),
    CONSTRAINT fk_region_course_course
        FOREIGN KEY (course_id) REFERENCES course (course_id)
);

COMMENT ON TABLE theme IS '테마';
COMMENT ON COLUMN theme.theme_id IS '테마 식별자';
COMMENT ON COLUMN theme.name IS '테마 이름';

COMMENT ON TABLE course_theme IS '코스 테마';
COMMENT ON COLUMN course_theme.course_theme_id IS '코스 테마 식별자';
COMMENT ON COLUMN course_theme.course_id IS '코스 식별자';
COMMENT ON COLUMN course_theme.theme_id IS '테마 식별자';

COMMENT ON TABLE region_course IS '지역 코스';
COMMENT ON COLUMN region_course.region_course_id IS '지역 코스 식별자';
COMMENT ON COLUMN region_course.region_id IS '지역 식별자';
COMMENT ON COLUMN region_course.course_id IS '코스 식별자';
