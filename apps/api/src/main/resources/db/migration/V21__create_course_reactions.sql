CREATE TABLE course_member_like (
    course_member_like_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INTEGER NOT NULL,
    member_id VARCHAR(36) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_course_member_like_course
        FOREIGN KEY (course_id) REFERENCES course (course_id),
    CONSTRAINT fk_course_member_like_member
        FOREIGN KEY (member_id) REFERENCES member (member_id)
);

CREATE TABLE course_scrap (
    course_scrap_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id VARCHAR(36) NOT NULL,
    course_id INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL,
    is_delete BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_course_scrap_member
        FOREIGN KEY (member_id) REFERENCES member (member_id),
    CONSTRAINT fk_course_scrap_course
        FOREIGN KEY (course_id) REFERENCES course (course_id)
);

COMMENT ON TABLE course_member_like IS '코스 좋아요';
COMMENT ON COLUMN course_member_like.course_member_like_id IS '코스 좋아요 식별자';
COMMENT ON COLUMN course_member_like.course_id IS '코스 식별자';
COMMENT ON COLUMN course_member_like.member_id IS '회원 식별자';
COMMENT ON COLUMN course_member_like.created_at IS '생성 시각';

COMMENT ON TABLE course_scrap IS '코스 스크랩';
COMMENT ON COLUMN course_scrap.course_scrap_id IS '코스 스크랩 식별자';
COMMENT ON COLUMN course_scrap.member_id IS '회원 식별자';
COMMENT ON COLUMN course_scrap.course_id IS '코스 식별자';
COMMENT ON COLUMN course_scrap.is_active IS '활성 여부';
COMMENT ON COLUMN course_scrap.is_delete IS '삭제 여부';
COMMENT ON COLUMN course_scrap.created_at IS '생성 시각';
COMMENT ON COLUMN course_scrap.updated_at IS '수정 시각';
COMMENT ON COLUMN course_scrap.deleted_at IS '삭제 시각';
